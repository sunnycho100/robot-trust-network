"""Build intake/carda_b.yaml for the held-out CarDA subset-B WS30 recordings (full ~4-min cycle, 7 SOP steps).

Only the SOP text is taken from the annotation workbook (no timestamps). Part masses are engineering estimates.
    python scripts/make_carda_b_intake.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from make_carda_intake import sop_for  # noqa: E402

PARTS = [  # name, keywords, mass_kg, precision_mm, basis, flexible
    ("door speaker (165 mm woofer)", ["speaker"], 0.8, 1.0, "estimate: 6.5-in automotive door woofers ~0.5-1.0 kg", False),
    ("speaker frame / grille ring", ["speaker frame", "frame"], 0.1, 1.0, "estimate: moulded plastic ring <0.15 kg", False),
    ("interior door trim panel", ["door panel"], 2.5, 2.0, "estimate: injection-moulded door trim panels ~2-4 kg", False),
    ("window control switch panel", ["window control"], 0.2, 1.0, "estimate: switch bezel + connector ~0.1-0.3 kg", False),
    ("anti-vibration pad", ["anti-vibration", "pad"], 0.05, 3.0, "estimate: foam/butyl pad <0.1 kg", True),
]


def main() -> None:
    xl = next((ROOT / "data/carda_b/ws30").glob("annotation_data_*.xlsx"))
    intake = {
        "customer": {"name": "CarDA demo line, held-out recordings (subset B)", "product": "car front door",
                     "source": "https://zenodo.org/records/14644367 (CC BY 4.0)"},
        "line": {"takt_s": 240, "paced": True, "shifts_per_day": 2, "hours_per_shift": 8, "days_per_year": 250,
                 "hourly_wage_usd": None},
        "cameras": {"calibration": "file", "file": "data/carda/cameras_calibration.xlsx"},
        "default_part": {"name": "component", "mass_kg": 0.5, "precision_mm": 2.0,
                         "basis": "default estimate when a step names no known part", "flexible": False},
        "stations": [{"name": "WS30", "conveyor": {"present": True, "polygon_xy": None, "direction_xy": None},
                      "sop": sop_for(xl),
                      "parts": [{"name": n, "keywords": k, "mass_kg": m, "precision_mm": p, "basis": b, "flexible": f}
                                for n, k, m, p, b, f in PARTS]}],
    }
    out = ROOT / "intake" / "carda_b.yaml"
    out.write_text("# Generated by scripts/make_carda_b_intake.py - SOP text only, no annotation timestamps.\n"
                   + yaml.safe_dump(intake, sort_keys=False, allow_unicode=True, width=120))
    print(out, [s["step"] for s in intake["stations"][0]["sop"]])


if __name__ == "__main__":
    main()
