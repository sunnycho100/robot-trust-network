"""Build intake/carda.yaml: what a factory would hand us, reconstructed from CarDA *without any timestamps*.

- SOP: ordered standard-work steps and their outline-numbered activity text (annotation workbook columns A-C
  only; Start/End and EAWS columns are deliberately dropped). Nesting is kept, repeated lines are not de-duplicated.
- Parts: engineering estimates of the door components (previously hard-coded in s2_elements/parts.py).
- Line facts from the Zenodo record (4-min paced conveyor line).
    python scripts/make_carda_intake.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rcd.s2_elements.parts import DEFAULT_PART, FLEXIBLE, PARTS  # noqa: E402


_OUTLINE = re.compile(r"^\d+(?:\.\d+)*$")


def _outline_rows(df: pd.DataFrame) -> dict[str, list[tuple[str, str]]]:
    """{step name: [(outline id, text)]} of one sheet, in sheet order. Ids that are not a valid outline number of
    the step (Excel turned some into times, e.g. 0.2152...) or are missing get the next top-level id of the step."""
    steps: dict[str, list[tuple[str, str]]] = {}
    cur, stepno, top = None, "0", 0
    for _, r in df.iloc[3:].iterrows():
        if isinstance(r.iloc[0], str) and r.iloc[0].strip():
            cur = r.iloc[0].strip()
            m = re.match(r"\s*(\d+)", cur)
            stepno, top = (m.group(1) if m else "0"), 0
            steps.setdefault(cur, [])
        if cur and isinstance(r.iloc[2], str) and r.iloc[2].strip():
            aid = str(r.iloc[1]).strip() if r.iloc[1] is not None else ""
            if aid.endswith(".0"):
                aid = aid[:-2]
            if not (_OUTLINE.match(aid) and aid.split(".")[0] == stepno and aid.count(".") >= 1):
                aid = f"{stepno}.{top + 1}"
            if aid.count(".") == 1:
                top = int(aid.split(".")[1])
            steps[cur].append((aid, " ".join(r.iloc[2].split())))
    return steps


def sop_for(xlsx: Path) -> list[dict]:
    """Ordered SOP steps with their outline-numbered activity lines ("3.13.1 Take 1 screw from the pouch").
    The nesting (outline numbers) is kept and repeated lines are NOT merged: a sub-activity that occurs under two
    parents is listed twice. All sheets of a workbook carry the same template per step; the first sheet that has
    the step is used (later sheets only add steps that the first one lacks)."""
    steps: dict[str, list[tuple[str, str]]] = {}
    for _, df in pd.read_excel(xlsx, sheet_name=None, header=None).items():
        for k, rows in _outline_rows(df).items():
            if k not in steps or (not steps[k] and rows):
                steps[k] = rows
    order = sorted(steps, key=lambda k: int(re.match(r"\s*(\d+)", k).group(1)) if re.match(r"\s*(\d+)", k) else 99)
    return [{"step": k, "text": k.split(".", 1)[-1].strip(), "activities": [f"{a} {t}" for a, t in steps[k]]}
            for k in order]


def main() -> None:
    stations = []
    for ws in ("ws10", "ws20", "ws30"):
        xl = next((ROOT / "data/carda" / ws).glob("annotation_data_*.xlsx"))
        sop = sop_for(xl)
        blob = " ".join([s["step"] + " " + " ".join(s["activities"]) for s in sop]).lower()
        parts = [{"name": name, "keywords": [kw], "mass_kg": kg, "precision_mm": prec, "basis": basis,
                  "flexible": kw in FLEXIBLE} for kw, name, kg, prec, basis in PARTS if kw in blob]
        stations.append({"name": ws.upper(), "conveyor": {"present": True, "polygon_xy": None, "direction_xy": None},
                         "sop": sop, "parts": parts})
    name, kg, prec, basis = DEFAULT_PART
    intake = {
        "customer": {"name": "CarDA demo line (Stellantis CRF, Melfi)", "product": "car front door",
                     "source": "https://zenodo.org/records/14644367 (CC BY 4.0)"},
        "line": {"takt_s": 240, "paced": True, "shifts_per_day": 2, "hours_per_shift": 8, "days_per_year": 250,
                 "hourly_wage_usd": None},
        "cameras": {"calibration": "file", "file": "data/carda/cameras_calibration.xlsx"},
        "default_part": {"name": name, "mass_kg": kg, "precision_mm": prec, "basis": basis, "flexible": False},
        "stations": stations,
    }
    out = ROOT / "intake" / "carda.yaml"
    out.write_text("# Generated by scripts/make_carda_intake.py - no timestamps from the annotation are included.\n"
                   + yaml.safe_dump(intake, sort_keys=False, allow_unicode=True, width=120))
    print(out, sum(len(s["sop"]) for s in stations), "SOP steps")


if __name__ == "__main__":
    main()
